def get_confirm_prompt(question: str, user_text: str) -> str:
    '''
    Бот показал найденную запись и спросил, действительно ли её удалять или менять.

    question — вопрос бота с описанием записи и что именно будет сделано,
    user_text — ответ пользователя.

    LLM возвращает JSON с подтверждением:
    {
        "confirm" : true
    }
    '''
    confirm_prompt = f"""
Ты — AI-модуль умного календаря-ассистента.

Бот нашёл запись в календаре пользователя и просит подтвердить действие.
Ответь, подтверждает ли пользователь это действие.

========================================
1. ВОПРОС БОТА
========================================

{question}

========================================
2. ОТВЕТ ПОЛЬЗОВАТЕЛЯ
========================================

{user_text}

========================================
3. ФОРМАТ ОТВЕТА
========================================

Верни строго один валидный JSON-объект без Markdown и пояснений:

{{
    "confirm": true
}}

- confirm: true — пользователь явно согласен («да», «давай», «точно»,
  «удаляй», «переноси», «подтверждаю», «ок»).
- confirm: false — во всех остальных случаях: отказ («нет», «не надо»,
  «отмена», «оставь»), сомнение, вопрос, неопределённый ответ
  или сообщение не по теме.
- Никогда не выдумывай согласие: при любом сомнении ставь false.
- Ровно одно поле confirm. Других полей и текста вне JSON не должно быть.

Верни только итоговый JSON-объект.
"""

    return confirm_prompt
