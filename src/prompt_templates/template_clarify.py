import datetime


def get_clarify_prompt(
    scope_text: str,
    question: str,
    utc_offset: int | float | datetime.timedelta = 3,
) -> str:
    '''
    Сужение скоупа: под расплывчатое описание удаляемой/изменяемой задачи
    подошло несколько записей, пользователь дал уточнение.

    scope_text — единственная строка с кандидатами в урезанном скоупе:
    не более 10 записей, по 5 в каждой (задачи и встречи), со сквозной нумерацией.
    question — уточнение пользователя.

    LLM возвращает JSON с номерами подходящих записей:
    {
        "suitable" : [1, 4, 9]
    }
    '''
    if not isinstance(utc_offset, datetime.timedelta):
        utc_offset = datetime.timedelta(hours=utc_offset)

    # Смещение передаётся в промпт внутри current_date, например «... 14:00 UTC+03:00»
    user_datetime = datetime.datetime.now(datetime.timezone(utc_offset))
    current_date = user_datetime.strftime('%Y-%m-%d (%A) %H:%M %Z')

    # Границы недель считаем сами: модель путается с «на этой неделе» в пятницу,
    # а неверная граница оставляет в скоупе не те записи
    week_start = user_datetime.date() - datetime.timedelta(days=user_datetime.weekday())
    week_end = week_start + datetime.timedelta(days=6)
    next_week_start = week_start + datetime.timedelta(days=7)
    next_week_end = next_week_start + datetime.timedelta(days=6)
    weeks = (
        f"Текущая неделя (понедельник–воскресенье): {week_start:%Y-%m-%d} — {week_end:%Y-%m-%d}.\n"
        f"Следующая неделя (понедельник–воскресенье): {next_week_start:%Y-%m-%d} — {next_week_end:%Y-%m-%d}."
    )

    clarify_prompt = f"""
Ты — AI-модуль умного календаря-ассистента.

Пользователь описал задачу или встречу расплывчато, и под его описание
подошло несколько записей календаря. Бот показал ему кандидатов,
а пользователь ответил уточнением.

Твоя задача — по списку кандидатов и уточнению пользователя определить,
какие записи он имеет в виду.

Текущие дата и время пользователя: {current_date}.
Часть «UTC+ЧЧ:ММ» — смещение часового пояса пользователя относительно UTC.
Даты в записях указаны в местном времени пользователя:
сравнивай их с текущей датой пользователя без перевода.

{weeks}

Верни строго один валидный JSON-объект.
Не добавляй Markdown, пояснения или текст вне JSON.

========================================
1. СПИСОК КАНДИДАТОВ
========================================

{scope_text}

Записи идут блоками — сначала задачи, затем встречи — и пронумерованы
сквозной нумерацией. Записей не больше десяти: не более пяти задач
и не более пяти встреч. Номер в строке — тот же номер,
который нужно вернуть в поле suitable.

========================================
2. ФОРМАТ ОТВЕТА
========================================

{{
    "suitable": [1, 4, 9]
}}

- Ровно одно поле suitable — массив номеров выбранных записей.
- Номера — целые числа без кавычек, от 1 до количества записей в списке.
- Номера, которых нет в списке, не возвращай.
- Не добавляй другие поля, пояснения и текст вне JSON.
- Для отсутствующих значений используй пустой массив, а не null.

========================================
3. ПРАВИЛА ОТБОРА
========================================

- Отбирай записи, которые удовлетворяют уточнению: совпадения по смыслу
  достаточно, точное совпадение слов не требуется. Учитывай синонимы
  и близкие по смыслу формулировки.
- Учитывай тип записи (задача или встреча), дату, время и имена людей.
- Относительные даты в уточнении («сегодня», «завтра», «в пятницу»)
  считай от текущей даты пользователя: {current_date}.
- Неделя начинается с понедельника. «На этой неделе» — текущая неделя,
  «на следующей» — следующая; их границы даны выше. Запись попадает в такую
  неделю, только если её дата лежит между границами включительно:
  дата записи — не раньше понедельника и не позже воскресенья.
- Отбирай только те записи, даты которых удовлетворяют уточнению:
  условие про неделю или период — жёсткое ограничение, а не повод
  добавить близкие по смыслу записи.
- Под уточнение может подойти несколько записей: верни все подходящие,
  не ограничиваясь одной.
- Не придумывай записи, которых нет в списке.
- Если уточнение подходит всем записям — верни все номера.
- Если не подходит ни одна запись — верни {{"suitable": []}}.
- В уточнении могут быть слова, не относящиеся к выбору записи:
  опирайся только на то, что помогает отличить записи друг от друга.

========================================
4. ПРИМЕРЫ
========================================

Пример. Список кандидатов:

Задачи:
1. Купить подарок коллеге, суббота 31 октября 2026
2. Оплатить страховку, четверг 5 ноября 2026

Встречи:
3. Встреча с Ольгой, понедельник 2 ноября 2026

Уточнение: «встреча в понедельник»
→ {{"suitable": [3]}}

Уточнение: «оплатить»
→ {{"suitable": [2]}}

Уточнение: «и то, и другое»
→ {{"suitable": [2, 3]}}

Уточнение: «ничего из этого»
→ {{"suitable": []}}

Номера в примерах относятся только к списку этого примера.
В ответе используй номера из раздела 1.

========================================
5. ФИНАЛЬНАЯ ПРОВЕРКА
========================================

1. В JSON ровно одно поле suitable — массив целых чисел.
2. Каждый номер есть в списке кандидатов.
3. JSON синтаксически корректен и разбирается через json.loads().

========================================
УТОЧНЕНИЕ ПОЛЬЗОВАТЕЛЯ
========================================

{question}

Верни только итоговый JSON-объект.
"""

    return clarify_prompt
