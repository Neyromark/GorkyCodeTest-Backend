import datetime
from zoneinfo import ZoneInfo


def get_reminder_time(
    user_text: str,
    event_date: datetime.date | None = None,
    event_time: datetime.time | None = None,
) -> str:
    '''
    Промпт для извлечения момента напоминания из ответа пользователя
    на вопрос «Во сколько вам напомнить об этой задаче?».

    LLM возвращает JSON из даты и времени напоминания:
    {
        "time" : "HH:MM" или null,
        "date" : "YYYY-MM-DD" или null
    }
    Строки затем приводятся к TimeValue и DateValue в key_func/reminder.py.

    event_date и event_time — дата и время самой задачи, если они известны:
    нужны для ответов вроде «за час до начала» или «накануне».
    '''
    moscow_datetime = datetime.datetime.now().astimezone(ZoneInfo("Europe/Moscow"))
    current_date = moscow_datetime.strftime('%Y-%m-%d (%A) %H:%M')

    event_date_text = event_date.isoformat() if event_date is not None else "не указана"
    event_time_text = event_time.strftime('%H:%M') if event_time is not None else "не указано"

    reminder_prompt = f"""
Ты — AI-модуль умного календаря-ассистента.

Пользователь только что создал задачу, и бот спросил его:
«Во сколько вам напомнить об этой задаче?»

Твоя задача — по ответу пользователя определить дату и время напоминания.

Сегодняшняя дата и текущее время (Москва): {current_date}.

Сведения о задаче:
- дата задачи: {event_date_text};
- время задачи: {event_time_text}.

Верни строго один валидный JSON-объект.
Не добавляй Markdown, пояснения или текст вне JSON.

========================================
1. ФОРМАТ ОТВЕТА
========================================

{{
    "time": "HH:MM или null",
    "date": "YYYY-MM-DD или null"
}}

- time: строка формата HH:MM в 24-часовом формате, без секунд и временной зоны.
- date: строка формата YYYY-MM-DD.
- Ровно два поля: time и date. Не добавляй других полей.
- Для отсутствующих значений используй JSON null, а не строку "null".

========================================
2. ПРАВИЛА ОПРЕДЕЛЕНИЯ ВРЕМЕНИ
========================================

Абсолютное время:
- «В 9», «в 9 утра», «в девять» → "09:00".
- «В 6 вечера», «в шесть вечера», «в 18» → "18:00".
- «В полдень» → "12:00", «в полночь» → "00:00".
- «В половине восьмого» → "07:30", если из контекста не ясно, что это вечер.
- «Без четверти девять» → "08:45".
- Число без уточнения от 1 до 6 («в 3», «в пять») считай дневным/вечерним временем
  (15:00, 17:00), если не сказано «утра» или «ночи».

Приблизительное время суток (если точное время не названо):
- «утром» → "09:00";
- «днём» → "13:00";
- «вечером» → "19:00";
- «ночью» → "22:00".

Относительно текущего момента:
- «Через час», «через 30 минут», «через 2 часа» → прибавь срок к текущему времени.

Относительно задачи (используй дату и время задачи из сведений выше):
- «За час», «за 15 минут», «за полчаса до начала» → вычти срок из даты и времени задачи.
- «Накануне», «за день», «за два дня» → дата задачи минус указанное число дней;
  время — названное пользователем, иначе "09:00" (время задачи НЕ переносится).
- «В день задачи», «в тот же день» → дата задачи; время — названное пользователем,
  иначе "09:00".
- Если ответ относится к задаче, но дата или время задачи, нужные для расчёта,
  не указаны, верни null в полях, которые нельзя вычислить.

========================================
3. ПРАВИЛА ОПРЕДЕЛЕНИЯ ДАТЫ
========================================

- «Сегодня» → сегодняшняя дата, «завтра» → завтрашняя, «послезавтра» → через два дня.
- Дни недели («в пятницу») → ближайший будущий такой день.
- Конкретная дата («25 октября», «25.10») → эта дата текущего года;
  если она уже прошла, следующего года.
- Если пользователь назвал только время, без даты:
  - если дата задачи известна, выбери дату задачи, если это время ещё не наступило
    и не позже начала задачи; иначе сегодняшнюю дату;
  - если дата задачи не известна, выбери сегодняшнюю дату, если это время сегодня
    ещё не наступило, иначе завтрашнюю.
- ПРАВИЛО ДНЯ БЕЗ ВРЕМЕНИ: если пользователь назвал день, но не назвал ни время,
  ни время суток («завтра», «в пятницу», «25 октября», «накануне», «за день»),
  time = "09:00". Не подставляй вместо этого время задачи или текущее время.

========================================
4. ОТКАЗ И НЕПОНЯТНЫЙ ОТВЕТ
========================================

Верни {{"time": null, "date": null}}, если:
- пользователь отказывается от напоминания («не надо», «не напоминай», «нет»);
- ответ не содержит даты, времени или срока и не позволяет их определить;
- ответ не относится к вопросу.

Не придумывай время, которого нет в ответе пользователя,
кроме правил по умолчанию из разделов 2 и 3.

========================================
5. ПРИМЕРЫ
========================================

Пусть сейчас 2026-10-28 (Wednesday) 14:00,
дата задачи 2026-10-30, время задачи 18:00.

«В 9 утра» → {{"time": "09:00", "date": "2026-10-30"}}
«Завтра в 10» → {{"time": "10:00", "date": "2026-10-29"}}
«За час» → {{"time": "17:00", "date": "2026-10-30"}}
«Накануне» → {{"time": "09:00", "date": "2026-10-29"}}
«Накануне вечером» → {{"time": "19:00", "date": "2026-10-29"}}
«Завтра» → {{"time": "09:00", "date": "2026-10-29"}}
«Через полчаса» → {{"time": "14:30", "date": "2026-10-28"}}
«В пятницу» → {{"time": "09:00", "date": "2026-10-30"}}
«Не надо» → {{"time": null, "date": null}}

В итоговом JSON используй реальные вычисленные значения
относительно текущей даты и сведений о задаче, а не значения из примеров.

========================================
6. ФИНАЛЬНАЯ ПРОВЕРКА
========================================

1. В JSON ровно два поля: time и date.
2. time имеет формат HH:MM или null, date имеет формат YYYY-MM-DD или null.
3. Относительные сроки рассчитаны от текущего времени или от времени задачи.
4. Момент напоминания не в прошлом.
5. JSON синтаксически корректен и разбирается через json.loads().

========================================
ОТВЕТ ПОЛЬЗОВАТЕЛЯ
========================================

{user_text}

Верни только итоговый JSON-объект.
"""

    return reminder_prompt
